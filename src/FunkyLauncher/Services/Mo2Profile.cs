using System.Text;
using System.Text.RegularExpressions;
using FunkyLauncher.Core;

namespace FunkyLauncher.Services;

/// <summary>
/// Writes the MO2 profile of a modlist installed from a Nexus list (Starfield): modlist.txt, plugins.txt and
/// loadorder.txt from the modlist's order file, keeping only the mods that are on disk and wanted (base always;
/// HD / Russian / 18+ when the player turned them on), and the profile's game INI.
/// The player's own mods (folders the lists don't know) keep their place on top and their on/off state.
/// </summary>
public static partial class Mo2Profile
{
    private const string Header = "# This file was automatically generated by Mod Organizer.";

    public static string ProfileDir(Settings s, Modlist m) => Path.Combine(s.InstallDir(m), "profiles", m.Mo2Profile);

    /// <summary>Is this modlist installed from Nexus lists (no .wabbajack file)?</summary>
    public static bool IsNexusList(Modlist m) => m.Installer == "nexus";

    /// <summary>Folder → wanted (true) / known but not wanted (false), for every mod of every pack.</summary>
    private static Dictionary<string, bool> Wanted(Settings s, Modlist m)
    {
        var map = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
        var replaced = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var mainId = Addons.Base(m.Id)?.AddonId;
        foreach (var a in Addons.All(m.Id))
        {
            var isMain = a.AddonId == mainId;
            var p = AddonService.Prefs(s, a);
            var on = isMain || p.On;
            var wanted = on ? AddonService.Wanted(a, p.Level2).Select(x => x.Id).ToHashSet() : new HashSet<string>();
            foreach (var x in a.Mods)
            {
                var w = isMain || wanted.Contains(x.Id);
                // e.g. the translation of an 18+ mod: on only while that pack is on too
                if (w && !string.IsNullOrEmpty(x.OnlyWith))
                    w = Addons.OfKind(m.Id, x.OnlyWith) is { } other && AddonService.Prefs(s, other).On;
                map[x.ModFolder] = map.TryGetValue(x.ModFolder, out var prev) ? prev || w : w;
                if (w) foreach (var r in x.Replaces) replaced.Add(r);
            }
        }
        foreach (var r in replaced) map[r] = false;
        return map;
    }

    private static string OursFile(Settings s, Modlist m) => Path.Combine(s.InstallDir(m), "funkylauncher-mods.txt");

    /// <summary>Mod folders the launcher itself installed into this modlist (so they can be told from the player's own).</summary>
    public static HashSet<string> Ours(Settings s, Modlist m)
    {
        try { if (File.Exists(OursFile(s, m))) return new HashSet<string>(File.ReadAllLines(OursFile(s, m)), StringComparer.OrdinalIgnoreCase); }
        catch { }
        return new HashSet<string>(StringComparer.OrdinalIgnoreCase);
    }

    public static void RememberOurs(Settings s, Modlist m, string folder)
    {
        try { if (!Ours(s, m).Contains(folder)) File.AppendAllText(OursFile(s, m), folder + "\r\n"); } catch { }
    }

    /// <summary>
    /// Before PLAY: makes our on-PC fixes (broken meshes) if the modlist has any — also for a modlist installed by an older
    /// launcher. Only the fix folder's own line is added to modlist.txt (switched on, above the MO2 mods so it wins);
    /// nothing else in the profile is touched, so the player's own changes stay as they are.
    /// </summary>
    public static void EnsureFixes(Settings s, Modlist m)
    {
        if (Addons.Order(m.Id) is not { NifFixes.Count: > 0 } order) return;
        var made = NifFixer.Apply(Path.Combine(s.InstallDir(m), "mods"), order.NifFixes);
        if (made.Count == 0) return;
        var listPath = Path.Combine(ProfileDir(s, m), "modlist.txt");
        if (!File.Exists(listPath)) return;
        var lines = File.ReadAllLines(listPath).ToList();
        var changed = false;
        foreach (var f in made)
        {
            if (lines.Any(l => l.Equals("+" + f, StringComparison.OrdinalIgnoreCase))) continue;
            lines.RemoveAll(l => l.Length > 1 && l[1..].Equals(f, StringComparison.OrdinalIgnoreCase));
            // after the header, the player's own mods and MO2's "*DLC / *Creation Club" lines: on top of our mods
            var at = lines.FindLastIndex(l => l.StartsWith('#') || l.StartsWith('*')) + 1;
            lines.Insert(at, "+" + f);
            RememberOurs(s, m, f);
            changed = true;
        }
        if (changed) File.WriteAllLines(listPath, lines);
    }

    public static void Write(Settings s, Modlist m, ModOrder order)
    {
        var profile = ProfileDir(s, m);
        Directory.CreateDirectory(profile);
        var modsDir = Path.Combine(s.InstallDir(m), "mods");
        var wanted = Wanted(s, m);
        var inOrder = new HashSet<string>(order.Modlist, StringComparer.OrdinalIgnoreCase);
        bool OnDisk(string folder) => Directory.Exists(Path.Combine(modsDir, folder));

        // ---- our fixes made on this PC from the authors' own files (broken meshes): an extra mod folder, switched on
        foreach (var folder in NifFixer.Apply(modsDir, order.NifFixes))
        {
            wanted[folder] = true;
            RememberOurs(s, m, folder);
        }

        // ---- modlist.txt (top = highest priority)
        var listPath = Path.Combine(profile, "modlist.txt");
        var old = File.Exists(listPath) ? File.ReadAllLines(listPath) : Array.Empty<string>();
        var lines = new List<string> { Header };
        var ours = Ours(s, m);
        foreach (var l in old)
        {
            // the player's own mods and MO2's own lines ("*Unmanaged: …") stay as they were, on top;
            // a mod we installed that a newer list dropped is switched off (its files stay)
            if (l.Length < 2 || l.StartsWith('#')) continue;
            var name = l[1..];
            if (inOrder.Contains(name) || wanted.ContainsKey(name)) continue;
            lines.Add(ours.Contains(name) && l[0] == '+' ? "-" + name : l);
        }
        // pack mods the order file forgot: on top too, so they win (and show up in a report)
        foreach (var (folder, w) in wanted)
            if (!inOrder.Contains(folder) && OnDisk(folder)) lines.Add((w ? "+" : "-") + folder);
        foreach (var folder in order.Modlist)
            if (OnDisk(folder)) lines.Add((wanted.TryGetValue(folder, out var w) && w ? "+" : "-") + folder);
        WriteIfChanged(listPath, lines);

        // ---- plugins.txt / loadorder.txt
        var enabledMods = lines.Where(l => l.StartsWith('+')).Select(l => l[1..]).ToList();
        var available = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var folder in enabledMods)
        {
            var dir = Path.Combine(modsDir, folder);
            if (!Directory.Exists(dir)) continue;
            foreach (var f in Directory.EnumerateFiles(dir))
                if (IsPlugin(f)) available.Add(Path.GetFileName(f));
        }
        var gamePath = GamePath(s.InstallDir(m));
        var data = gamePath == null ? null : Path.Combine(gamePath, "Data");
        bool InGame(string p) => data != null && File.Exists(Path.Combine(data, p));

        var plugins = new List<string> { Header };
        var order2 = new List<string>();
        var off = new HashSet<string>(order.PluginsOff, StringComparer.OrdinalIgnoreCase);
        foreach (var p in order.Plugins)
        {
            if (!available.Contains(p) && !InGame(p)) continue;
            plugins.Add(off.Contains(p) ? p : "*" + p);
            order2.Add(p);
        }
        // plugins of enabled mods that the order file does not list: switched off, at the end (never guessed into the order)
        var listed = new HashSet<string>(order2, StringComparer.OrdinalIgnoreCase);
        foreach (var p in available.Where(p => !listed.Contains(p)).OrderBy(p => p, StringComparer.OrdinalIgnoreCase))
        {
            plugins.Add(p);
            order2.Add(p);
        }
        WriteIfChanged(Path.Combine(profile, "plugins.txt"), plugins);
        WriteIfChanged(Path.Combine(profile, "loadorder.txt"), new[] { Header }.Concat(order2).ToList());

        // ---- the profile's game INI (written whole from the order file; patches below may add to it)
        if (order.Ini.Count > 0 && m.Mo2IniName.Length > 0)
        {
            var lang = Addons.Russian(m.Id) is { } ru && AddonService.Prefs(s, ru).On ? "ru" : "en";
            WriteIfChanged(Path.Combine(profile, m.Mo2IniName), order.Ini.Select(l => l.Replace("{lang}", lang)).ToList());
        }

        // ---- INI values in mod files or ("@profile") in the profile's INI (idempotent: set every time)
        var mainId = Addons.Base(m.Id)?.AddonId;
        var patches = order.FilePatches.Concat(Addons.All(m.Id)
            .Where(a => a.AddonId == mainId || AddonService.Prefs(s, a).On).SelectMany(a => a.FilePatches));
        foreach (var fp in patches)
        {
            if (!string.IsNullOrEmpty(fp.OnlyWith) && !(Addons.OfKind(m.Id, fp.OnlyWith) is { } w && AddonService.Prefs(s, w).On)) continue;
            var modDir = fp.ModFolder == "@profile" ? profile : Path.Combine(modsDir, fp.ModFolder);
            if (!Directory.Exists(modDir)) continue;
            var f = Path.Combine(modDir, fp.File.Replace('/', Path.DirectorySeparatorChar));
            // some mods write their INI only on the first game start (Baka Framework): create it with our value now
            if (!File.Exists(f)) { Directory.CreateDirectory(Path.GetDirectoryName(f)!); File.WriteAllText(f, ""); }
            SetIni(f, fp.Section, fp.Key, fp.Value);
        }

        // ---- the other profile INIs MO2 expects (otherwise it warns on every start)
        foreach (var ini in m.Mo2ProfileInis)
        {
            var dst = Path.Combine(profile, ini);
            if (File.Exists(dst) || ini.Equals(m.Mo2IniName, StringComparison.OrdinalIgnoreCase)) continue;
            var mine = m.MyGamesFolder.Length == 0 ? null : Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "My Games", m.MyGamesFolder, ini);
            if (mine != null && File.Exists(mine)) File.Copy(mine, dst);
            else File.WriteAllText(dst, "");
        }
    }

    /// <summary>Sets key=value in [section] of an INI file (adds the section / key if missing), keeping everything else.</summary>
    public static void SetIni(string file, string section, string key, string value)
    {
        var lines = File.ReadAllLines(file).ToList();
        var inSection = false;
        var sectionAt = -1;
        for (var i = 0; i < lines.Count; i++)
        {
            var t = lines[i].Trim();
            if (t.StartsWith('[') && t.EndsWith(']'))
            {
                if (inSection) { lines.Insert(i, $"{key}={value}"); Save(); return; }
                inSection = t[1..^1].Trim().Equals(section, StringComparison.OrdinalIgnoreCase);
                if (inSection) sectionAt = i;
                continue;
            }
            if (!inSection) continue;
            var eq = t.IndexOf('=');
            if (eq > 0 && t[..eq].Trim().Equals(key, StringComparison.OrdinalIgnoreCase))
            {
                if (t[(eq + 1)..].Trim() == value) return;
                lines[i] = $"{key}={value}";
                Save();
                return;
            }
        }
        if (sectionAt < 0) { lines.Add($"[{section}]"); }
        lines.Add($"{key}={value}");
        Save();

        void Save()
        {
            if (!File.Exists(file + ".orig")) File.Copy(file, file + ".orig");
            File.WriteAllLines(file, lines, new UTF8Encoding(false));
        }
    }

    private static bool IsPlugin(string f)
    {
        var e = Path.GetExtension(f).ToLowerInvariant();
        return e is ".esm" or ".esp" or ".esl";
    }

    private static void WriteIfChanged(string path, List<string> lines)
    {
        var text = string.Join("\r\n", lines) + "\r\n";
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        if (File.Exists(path)) File.Copy(path, path + ".before-launcher", overwrite: true);
        File.WriteAllText(path, text, new UTF8Encoding(false));
    }

    [GeneratedRegex(@"^gamePath=@ByteArray\((?<p>.*)\)\s*$", RegexOptions.Multiline)]
    private static partial Regex GamePathLine();

    /// <summary>The game folder written in the portable MO2 instance (ModOrganizer.ini), or null.</summary>
    public static string? GamePath(string installDir)
    {
        try
        {
            var ini = Path.Combine(installDir, "ModOrganizer.ini");
            if (!File.Exists(ini)) return null;
            var m = GamePathLine().Match(File.ReadAllText(ini));
            return m.Success ? m.Groups["p"].Value.Replace(@"\\", @"\") : null;
        }
        catch { return null; }
    }

    /// <summary>
    /// A fresh portable MO2 instance for the game: ModOrganizer.ini (game, profile, local INIs and saves,
    /// archive invalidation, no update checks), the executables (script extender first) and portable.txt.
    /// </summary>
    public static void WriteInstance(string installDir, Modlist m, string gamePath)
    {
        var g = gamePath.TrimEnd('\\');
        string Esc(string p) => p.Replace(@"\", @"\\");
        string Fwd(string p) => p.Replace('\\', '/');
        var sb = new StringBuilder();
        sb.Append("[General]\r\n");
        sb.Append($"gameName={m.Mo2GameName}\r\n");
        sb.Append($"gamePath=@ByteArray({Esc(g)})\r\n");
        sb.Append($"selected_profile=@ByteArray({m.Mo2Profile})\r\n");
        sb.Append("first_start=false\r\n\r\n");
        sb.Append("[Settings]\r\nprofile_local_inis=true\r\nprofile_local_saves=true\r\nprofile_archive_invalidation=true\r\ncheck_for_updates=false\r\n\r\n");
        // "This program requires Steam" — answered once as "Continue without starting Steam" (65536 = No):
        // a Steam copy starts Steam by itself, other copies don't need it
        sb.Append("[DialogChoices]\r\nsteamQuery=65536\r\n\r\n");
        var exes = m.Mo2Executables.Count > 0 ? m.Mo2Executables : new List<Mo2Exe> { new() { Title = m.Mo2Executable, Binary = m.GameExe } };
        sb.Append($"[customExecutables]\r\nsize={exes.Count}\r\n");
        for (var i = 0; i < exes.Count; i++)
        {
            var n = i + 1;
            sb.Append($"{n}\\title={exes[i].Title}\r\n{n}\\binary={Fwd(Path.Combine(g, exes[i].Binary))}\r\n{n}\\arguments=\r\n");
            sb.Append($"{n}\\workingDirectory={Fwd(g)}\r\n{n}\\ownicon=true\r\n{n}\\hide=false\r\n{n}\\toolbar=true\r\n");
        }
        File.WriteAllText(Path.Combine(installDir, "ModOrganizer.ini"), sb.ToString(), new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(installDir, "portable.txt"), "");
        Directory.CreateDirectory(Path.Combine(installDir, "mods"));
        Directory.CreateDirectory(Path.Combine(installDir, "overwrite"));
        Directory.CreateDirectory(Path.Combine(installDir, "profiles", m.Mo2Profile, "saves"));
    }
}
